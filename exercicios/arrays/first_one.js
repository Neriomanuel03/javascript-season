//criando uma lista e imprimir com arrays/vector
const lista = ["1", "2", "3", "4"];
lista.unshift ("3"); //adiciona o ele na primeira posicao
console.log(lista);


const numeros = ["1", "2", "3", "4"];
numeros.pop ("3"); //remove o ele na ultima posicao
console.log(numeros);

const final = ["1", "2", "3", "4"];
final.push ("3"); //adiciona o ele na ultima posicao
console.log(final);